
# 1. Variables
name = "Pooja"
age = 21
course = "Computer Science"
print("Name:", name)
print("Age:", age)
print("Course:", course)

# 2. Data Types
number = 100
price = 99.50
is_student = True
print(type(number))
print(type(price))
print(type(is_student))

# 3. String Operations
first_name = "Pooja"
last_name = "G"
full_name = first_name + " " + last_name
print("Full Name:", full_name)
print("Uppercase:", full_name.upper())
print("Lowercase:", full_name.lower())
print("Name Length:", len(full_name))

# 4. Type Conversion
number_text = "25"
number_value = int(number_text)
print(number_value + 5)

# 5. User Input
user_name = input("Enter your name: ")
print("Hello,", user_name)

# 6. Arithmetic Operations
a = 10
b = 3
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Remainder:", a % b)

# 7. String Slicing
message = "Python Programming"
print("First six characters:", message[:6])
print("Last eleven characters:", message[7:])

# 8. String Replacement
sentence = "I am learning Java"
print(sentence.replace("Java", "Python"))

# 9. F-Strings
student = "Pooja"
mark = 85
print(f"{student} scored {mark} marks")

# 10. Multiple Line String
description = """Python is easy to learn.
Python is useful for AI.
Python is used in backend development."""
print(description)

